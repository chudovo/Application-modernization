-- The schema after working through what the tests found.
CREATE EXTENSION IF NOT EXISTS citext;

CREATE TABLE customers (
    id            int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name          varchar(100) NOT NULL,
    -- citext: compared without regard to case, as every string was on SQL Server. Also makes the unique
    -- constraint reject Anna@Example.com when anna@example.com exists.
    email         citext NOT NULL,
    region        varchar(2) NOT NULL,
    vip           boolean NOT NULL DEFAULT false,
    note          varchar(10) NULL,
    last_order_at timestamp NULL,
    CONSTRAINT uq_customers_email UNIQUE (email)
);

CREATE TABLE orders (
    id          int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id int NOT NULL REFERENCES customers (id),
    placed_at   timestamp NOT NULL,
    items       int NOT NULL,
    total       numeric(19, 4) NOT NULL   -- what SQL Server's money is: four decimals
);

CREATE TABLE audit (
    id      int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    at      timestamp NOT NULL,
    message varchar(200) NOT NULL
);
